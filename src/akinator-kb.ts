export function pYes(animal: AnimalProfile, questionId: string): number {
  const value = animal.traits[questionId];
  return value ? TRAIT_P_YES[value] : 0.50;
}

export function traitConfidence(animal: AnimalProfile, questionId: string): number {
  const value = animal.traits[questionId];
  return value ? TRAIT_CONFIDENCE[value] : 0.30;
}

export function questionFamily(questionId: string): string {
  for (const family of QUESTION_FAMILIES) {
    if (family.questionIds.includes(questionId)) return family.id;
  }
  return "other";
}

export function localizedName(animal: AnimalProfile, language: Language): string {
  return animal.name[language] || animal.name.en;
}

